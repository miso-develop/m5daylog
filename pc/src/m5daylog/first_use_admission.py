"""#143 R5-FU: source-only supervised first-use admission checks.

This is a deterministic *negative* preflight, NOT enrollment, receipt
persistence, an authorization token, or a release sender. The supplied facts
must be established by independent, durable #119/Device/Windows evidence.
In particular, Python booleans and a CDC origin string are not attestation.
No caller in the CLI or watcher uses this module to send RELEASE_STORAGE.

The actual host intent consumption + dual-witness initialization/reservation
must be implemented as one fail-closed pre-send transaction under #89's
cross-process lock before release may be enabled.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from enum import Enum
from typing import Mapping

from .release import PreconditionBlocked


class PriorEnrollment(Enum):
    """Prior host state, established externally, BEFORE first-enrollment entry."""

    VERIFIED_NEVER_ENROLLED = "VERIFIED_NEVER_ENROLLED"
    ALREADY_ENROLLED = "ALREADY_ENROLLED"
    INDETERMINATE = "INDETERMINATE"


class CycleOrigin(Enum):
    SUPERVISED_FIRST_USE = "SUPERVISED_FIRST_USE"
    NORMAL_WAKE = "NORMAL_WAKE"


def _uuid(value: object) -> str:
    if not isinstance(value, str):
        raise PreconditionBlocked("first-use identity unqualified")
    try:
        canonical = str(uuid.UUID(value))
    except (ValueError, AttributeError, TypeError):
        raise PreconditionBlocked("first-use identity unqualified") from None
    if canonical != value:
        raise PreconditionBlocked("first-use identity noncanonical")
    return canonical


def _opaque(value: object) -> str:
    # Synthetic/session identifiers must never be printed in diagnostics.
    if (not isinstance(value, str) or not value or len(value) > 256
            or any(ord(char) < 33 or ord(char) > 126 for char in value)):
        raise PreconditionBlocked("first-use session evidence unqualified")
    return value


def parse_cycle_origin(status: object) -> CycleOrigin:
    """Strict R5 source-only proposed schema. Not a frozen CDC wire contract."""
    if not isinstance(status, Mapping):
        raise PreconditionBlocked("release origin missing")
    raw = status.get("releaseCycleOrigin")
    try:
        return CycleOrigin(raw)
    except (ValueError, TypeError):
        raise PreconditionBlocked("release origin missing or incompatible") from None


@dataclass(frozen=True)
class HostHistory:
    prior: PriorEnrollment
    ledger_exists: bool
    anchor_exists: bool
    independently_verified_never_enrolled: bool = False


@dataclass(frozen=True)
class InitialIntent:
    """Host-held supervised receipt; never generated by an arrival callback."""

    device_id: str = field(repr=False)
    physical_parent: str = field(repr=False)
    maintenance_session: str = field(repr=False)
    maintenance_attempt_id: str = field(repr=False)
    state: str = "UNCONSUMED"
    exact_human_permit_verified: bool = False
    device_physical_stage_verified: bool = False
    running_handler_verified: bool = False
    original_media_preserved: bool = False


@dataclass(frozen=True)
class MaintenanceReceipt:
    """Independent accepted #105 maintenance/Device-armed observations."""

    device_id: str = field(repr=False)
    physical_parent: str = field(repr=False)
    maintenance_session: str = field(repr=False)
    maintenance_attempt_id: str = field(repr=False)
    accepted_response_verified: bool = False
    exact_target_disappeared: bool = False
    device_shutdown_armed_verified: bool = False


@dataclass(frozen=True)
class InitialBootObservation:
    """New Device-owned boot observed after the maintenance release."""

    device_id: str = field(repr=False)
    current_physical_parent: str = field(repr=False)
    new_host_session: str = field(repr=False)
    cross_session_custody_verified: bool = False
    first_boot_transition_verified: bool = False
    current_run_terminal_pcm_verified: bool = False
    raw_wav_sync_durable: bool = False
    rtc_validity_verified: bool = False
    exact_target_verified: bool = False


@dataclass(frozen=True)
class FirstUseCandidate:
    """Pre-send planning tuple only. Does not consume any right or authorize CDC."""

    device_id: str = field(repr=False)
    release_cycle_id: str = field(repr=False)
    maintenance_attempt_id: str = field(repr=False)


def inspect_first_use_admission(
    *, status: Mapping[str, object], history: HostHistory,
    intent: InitialIntent, maintenance: MaintenanceReceipt,
    boot: InitialBootObservation,
) -> FirstUseCandidate:
    """Fail-closed inspection before a separately implemented durable mutation.

    All assertions represented by *_verified fields must have independently
    qualified receipts in the eventual integrator. This pure function neither
    reads nor changes the real DB, anchor, intent, Device, or Windows volume.
    """
    if not isinstance(history, HostHistory) or history.prior is not PriorEnrollment.VERIFIED_NEVER_ENROLLED:
        raise PreconditionBlocked("initial enrollment not independently qualified")
    if (type(history.ledger_exists) is not bool
            or type(history.anchor_exists) is not bool
            or history.ledger_exists or history.anchor_exists
            or history.independently_verified_never_enrolled is not True):
        raise PreconditionBlocked("host first-enrollment baseline unqualified")
    if not all(isinstance(obj, cls) for obj, cls in (
        (intent, InitialIntent), (maintenance, MaintenanceReceipt),
        (boot, InitialBootObservation),
    )):
        raise PreconditionBlocked("first-use evidence missing")
    if parse_cycle_origin(status) is not CycleOrigin.SUPERVISED_FIRST_USE:
        raise PreconditionBlocked("first-use origin mismatch")
    if (status.get("state") != "USB_SYNC"
            or status.get("rtcCorrectionPending") is not False):
        raise PreconditionBlocked("first-use Device status not qualified")

    device = _uuid(boot.device_id)
    if _uuid(intent.device_id) != device or _uuid(maintenance.device_id) != device:
        raise PreconditionBlocked("first-use Device identity mismatch")
    cycle = _uuid(status.get("releaseCycleId"))
    attempt = _uuid(intent.maintenance_attempt_id)
    if _uuid(maintenance.maintenance_attempt_id) != attempt:
        raise PreconditionBlocked("maintenance attempt correlation mismatch")

    pre_parent = _opaque(intent.physical_parent)
    pre_session = _opaque(intent.maintenance_session)
    if (_opaque(maintenance.physical_parent) != pre_parent
            or _opaque(maintenance.maintenance_session) != pre_session):
        raise PreconditionBlocked("maintenance session correlation mismatch")
    _opaque(boot.current_physical_parent)
    new_session = _opaque(boot.new_host_session)
    if new_session == pre_session:
        raise PreconditionBlocked("first-use host session not advanced")

    if (intent.state != "UNCONSUMED"
            or intent.exact_human_permit_verified is not True
            or intent.device_physical_stage_verified is not True
            or intent.running_handler_verified is not True
            or intent.original_media_preserved is not True):
        raise PreconditionBlocked("supervised first-use intent invalid or consumed")
    if (maintenance.accepted_response_verified is not True
            or maintenance.exact_target_disappeared is not True
            or maintenance.device_shutdown_armed_verified is not True):
        raise PreconditionBlocked("qualified maintenance release missing")
    if (boot.cross_session_custody_verified is not True
            or boot.first_boot_transition_verified is not True
            or boot.current_run_terminal_pcm_verified is not True
            or boot.raw_wav_sync_durable is not True
            or boot.rtc_validity_verified is not True
            or boot.exact_target_verified is not True):
        raise PreconditionBlocked("first-use boot and host proof incomplete")

    return FirstUseCandidate(device, cycle, attempt)
